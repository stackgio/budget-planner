"""Shortens the pauses in the voiceover without touching the speech.

Every silent gap longer than KEEP seconds (ffmpeg silencedetect, -35 dB, >= 0.18 s)
is cut down to KEEP by removing its middle. Writes the tightened audio and warp.js /
warp.json, which map video time back onto the original voiceover timeline so
index.html and sfx.py can keep their timings in original-voiceover seconds.

    python3 tighten.py voiceover.mp3 voiceover_tight.wav
"""
import json, re, subprocess, sys, wave
import numpy as np

KEEP, SR = 0.28, 48000
src, out = sys.argv[1], sys.argv[2]

log = subprocess.run(["ffmpeg", "-hide_banner", "-i", src, "-af", "silencedetect=noise=-35dB:d=0.18", "-f", "null", "-"],
                     capture_output=True, text=True).stderr
starts = [float(x) for x in re.findall(r"silence_start: ([0-9.]+)", log)]
ends = [float(x) for x in re.findall(r"silence_end: ([0-9.]+)", log)]
pauses = [[round(s, 3), round(e, 3)] for s, e in zip(starts, ends) if e - s > KEEP and s > 0.05]

pcm = subprocess.run(["ffmpeg", "-v", "quiet", "-i", src, "-ac", "1", "-ar", str(SR), "-f", "s16le", "-"],
                     capture_output=True).stdout
a = np.frombuffer(pcm, dtype=np.int16)
keep, cur = [], 0
for s, e in pauses:   # drop the middle of each long pause
    cut0, cut1 = int((s + KEEP / 2) * SR), int((e - KEEP / 2) * SR)
    keep.append(a[cur:cut0]); cur = cut1
keep.append(a[cur:])
b = np.concatenate(keep)
with wave.open(out, "wb") as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes(b.tobytes())

data = {"keep": KEEP, "pauses": pauses, "removed": round(sum(e - s - KEEP for s, e in pauses), 3),
        "original_duration": round(len(a) / SR, 3), "tight_duration": round(len(b) / SR, 3)}
json.dump(data, open("warp.json", "w"), indent=1)
open("warp.js", "w").write("// generated by tighten.py\nwindow.WARP = " + json.dumps(data) + ";\n")
print(json.dumps(data))
