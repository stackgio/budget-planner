/** Chapter marker: big numeral + label, e.g. "01 · EMERGENCY FUND". */
export const ChapterTag: React.FC<{n: string; label: string; at: number; exitAt?: number; palette: Palette; style?: React.CSSProperties}> = ({n, label, at, exitAt, palette, style}) => {
	const frame = useCurrentFrame();
	const {fps} = useVideoConfig();
	const p = spring({frame: frame - at, fps, config: springs.bouncy});
	const pl = spring({frame: frame - at - 5, fps, config: springs.snappy});
	const out = exitAt === undefined ? 0 : spring({frame: frame - exitAt, fps, config: springs.snappy});
	return (
		<div style={{position: 'absolute', display: 'flex', alignItems: 'center', gap: 20, fontFamily: story.font, opacity: 1 - out, transform: `translateY(${-out * 30}px)`, ...style}}>
			<div
				style={{
					width: 92,
					height: 92,
					borderRadius: 24,
					background: palette.accent,
					color: '#fff',
					fontSize: 46,
					fontWeight: 900,
					display: 'flex',
					alignItems: 'center',
					justifyContent: 'center',
					transform: `scale(${p}) rotate(${(1 - p) * -25}deg)`,
					letterSpacing: -1,
				}}
			>
				{n}
			</div>
			<div style={{overflow: 'hidden'}}>
				<div style={{fontSize: 30, fontWeight: 900, letterSpacing: 4, color: palette.muted, transform: `translateX(${(1 - pl) * -110}%)`}}>{label}</div>
			</div>
		</div>
	);
};

export type SfxName = 'whoosh' | 'whoosh-soft' | 'pop' | 'coin' | 'cash' | 'card' | 'paper' | 'thud' | 'stamp' | 'chime' | 'tick' | 'click';

/** One sound effect at a scene-local frame. Files are generated by scripts/make_sfx.py (original, royalty-free). */
export const SfxContext = React.createContext<{enabled: boolean; master: number}>({enabled: true, master: 1});

export const Sfx: React.FC<{at: number; name: SfxName; volume?: number}> = ({at, name, volume = 0.5}) => {
	const {enabled, master} = React.useContext(SfxContext);
	return enabled && master > 0 ? (
		<Sequence from={Math.max(0, Math.round(at))} durationInFrames={60} layout="none" name={`sfx:${name}`}>
			<Html5Audio src={staticFile(`sfx/${name}.wav`)} volume={volume * master} />
		</Sequence>
	) : null;
};
